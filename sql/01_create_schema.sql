-- Customer Shopping Behavior Analysis
-- PostgreSQL dimensional model (star schema)
-- Grain: one fact row per unique Customer ID in the supplied dataset.
-- The source dataset does not contain a purchase timestamp or transaction ID.

CREATE SCHEMA IF NOT EXISTS analytics_customer;

CREATE TABLE IF NOT EXISTS analytics_customer.dim_customer (
    customer_id INTEGER PRIMARY KEY,
    age SMALLINT NOT NULL,
    age_group VARCHAR(20) NOT NULL,
    gender VARCHAR(10) NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics_customer.dim_location (
    id_location INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    state_name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS analytics_customer.dim_shipping (
    id_shipping INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipping_type VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS analytics_customer.dim_frequency_buy (
    id_frequency_buy INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    frequency_name VARCHAR(30) NOT NULL UNIQUE,
    frequency_days SMALLINT NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics_customer.dim_payment_method (
    payment_method_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_method VARCHAR(25) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS analytics_customer.dim_product (
    id_product INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR(30) NOT NULL,
    category VARCHAR(30) NOT NULL,
    color VARCHAR(25) NOT NULL,
    size VARCHAR(4) NOT NULL,
    season VARCHAR(10) NOT NULL,
    CONSTRAINT uq_dim_product_description
        UNIQUE (product_name, category, color, size, season)
);

CREATE TABLE IF NOT EXISTS analytics_customer.fact_customer_purchase (
    id_fact BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL UNIQUE,
    payment_method_id INTEGER NOT NULL,
    id_location INTEGER NOT NULL,
    id_shipping INTEGER NOT NULL,
    id_frequency_buy INTEGER NOT NULL,
    id_product INTEGER NOT NULL,
    purchase_amount NUMERIC(10,2) NOT NULL CHECK (purchase_amount >= 0),
    review_rating NUMERIC(3,2) CHECK (review_rating BETWEEN 0 AND 5),
    subscription_status BOOLEAN NOT NULL,
    discount_applied BOOLEAN NOT NULL,
    previous_purchases INTEGER NOT NULL CHECK (previous_purchases >= 0),
    CONSTRAINT fk_fact_customer
        FOREIGN KEY (customer_id)
        REFERENCES analytics_customer.dim_customer (customer_id),
    CONSTRAINT fk_fact_payment_method
        FOREIGN KEY (payment_method_id)
        REFERENCES analytics_customer.dim_payment_method (payment_method_id),
    CONSTRAINT fk_fact_location
        FOREIGN KEY (id_location)
        REFERENCES analytics_customer.dim_location (id_location),
    CONSTRAINT fk_fact_shipping
        FOREIGN KEY (id_shipping)
        REFERENCES analytics_customer.dim_shipping (id_shipping),
    CONSTRAINT fk_fact_frequency
        FOREIGN KEY (id_frequency_buy)
        REFERENCES analytics_customer.dim_frequency_buy (id_frequency_buy),
    CONSTRAINT fk_fact_product
        FOREIGN KEY (id_product)
        REFERENCES analytics_customer.dim_product (id_product)
);

COMMENT ON TABLE analytics_customer.fact_customer_purchase IS
'One row per unique customer record in the supplied 3,900-row dataset; no purchase date is available.';
